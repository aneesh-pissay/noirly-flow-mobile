/**
 * App icons from the Noirly Flow web mark (design/brand/flow-mark.svg, copied
 * from noirly-flow/public/brand-mark.svg): a board whose cards thin out
 * column by column.
 *
 * Android 8+ gets an adaptive icon drawn as vectors, in the web theme's two
 * schemes — the launcher picks the one matching the system:
 *
 *   light  #8a6b00 gold on #faf8f2  (web "Warm Gold", light)
 *   dark   #ffe66d gold on #0a0a08  (web "Warm Gold", dark)
 *
 * plus a monochrome layer, so Android 13+ "Themed icons" tint it like the
 * system apps. The mark is 44dp wide inside the 108dp canvas — centred on the
 * card grid, well inside the 66dp safe zone every launcher mask keeps — so a
 * circle, squircle or teardrop never crops a card.
 *
 *   res/drawable/ic_launcher_foreground.xml            mark, @color/ic_launcher_mark
 *   res/drawable/ic_launcher_monochrome.xml            mark, for themed icons
 *   res/values(-night)/ic_launcher_colors.xml          the two schemes
 *   res/mipmap-anydpi-v26/ic_launcher(_round).xml      adaptive icon
 *   res/mipmap-<density>/ic_launcher(_round).png       Android 7 fallback (dark)
 *   fastlane/metadata/android/en-US/images/icon.png    Play listing icon (512)
 */
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { BRAND, ROOT, flowMarkSvg, openBrowser, render } from "./lib.mjs";

const RES = join(ROOT, "android/app/src/main/res");
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

export const SCHEMES = {
  light: { bg: "#faf8f2", mark: "#8a6b00" },
  dark: { bg: BRAND.bg, mark: BRAND.accent },
};

/* ---- Geometry, from flow-mark.svg (1024 viewBox) ---- */
const CARDS = [
  [196, 216], [196, 404], [196, 592],
  [420, 216], [420, 404],
  [644, 216],
];
const CARD = { w: 184, h: 152, r: 44 };
const BOX = { x: 196, y: 216, w: 828 - 196, h: 744 - 216 }; // 632 × 528

/** Width of the mark on the 108dp adaptive canvas. */
const MARK_DP = 44;
const K = MARK_DP / BOX.w;
const TX = 54 - (BOX.w * K) / 2 - BOX.x * K;
const TY = 54 - (BOX.h * K) / 2 - BOX.y * K;

function cardPath([x, y]) {
  const { w, h, r } = CARD;
  return (
    `M${x + r},${y}h${w - 2 * r}a${r},${r} 0,0 1,${r},${r}v${h - 2 * r}` +
    `a${r},${r} 0,0 1,-${r},${r}h-${w - 2 * r}a${r},${r} 0,0 1,-${r},-${r}` +
    `v-${h - 2 * r}a${r},${r} 0,0 1,${r},-${r}z`
  );
}

function markVector(fill) {
  const round = (n) => Math.round(n * 1000) / 1000;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/store-art/icons.mjs. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="${round(TX)}"
        android:translateY="${round(TY)}"
        android:scaleX="${round(K)}"
        android:scaleY="${round(K)}">
        <path
            android:fillColor="${fill}"
            android:pathData="${CARDS.map(cardPath).join("")}" />
    </group>
</vector>
`;
}

const ADAPTIVE = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/store-art/icons.mjs. Edit the script, not this file. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;

function colors({ bg, mark }, note) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/store-art/icons.mjs. ${note} -->
<resources>
    <color name="ic_launcher_background">${bg}</color>
    <color name="ic_launcher_mark">${mark}</color>
</resources>
`;
}

/** The mark centred on a tile, at the same proportions as the adaptive icon. */
function tile(size, scheme, radius) {
  // Mark width relative to the visible tile: 44dp of the 72dp a launcher shows.
  const markW = size * (MARK_DP / 72);
  const svg = markW * (1024 / BOX.w);
  // Centre the cards, not the SVG's viewBox (the cards sit a little high in it).
  const dy = ((512 - (BOX.y + BOX.h / 2)) / 1024) * svg;
  return `
  <div style="width:${size}px;height:${size}px;border-radius:${radius};overflow:hidden;background:${scheme.bg};
    display:flex;align-items:center;justify-content:center;">
    <div style="width:${svg}px;height:${svg}px;transform:translateY(${dy}px)">${flowMarkSvg(scheme.mark)}</div>
  </div>`;
}

// Vector adaptive icon.
mkdirSync(join(RES, "drawable"), { recursive: true });
mkdirSync(join(RES, "values-night"), { recursive: true });
mkdirSync(join(RES, "mipmap-anydpi-v26"), { recursive: true });
writeFileSync(join(RES, "drawable/ic_launcher_foreground.xml"), markVector("@color/ic_launcher_mark"));
// Themed icons use only the alpha of this layer; the system supplies the colour.
writeFileSync(join(RES, "drawable/ic_launcher_monochrome.xml"), markVector("#FFFFFFFF"));
writeFileSync(join(RES, "mipmap-anydpi-v26/ic_launcher.xml"), ADAPTIVE);
writeFileSync(join(RES, "mipmap-anydpi-v26/ic_launcher_round.xml"), ADAPTIVE);
writeFileSync(join(RES, "values/ic_launcher_colors.xml"), colors(SCHEMES.light, "Light scheme."));
writeFileSync(join(RES, "values-night/ic_launcher_colors.xml"), colors(SCHEMES.dark, "Dark scheme."));
// Superseded by the vector foreground and ic_launcher_colors.xml.
for (const stale of [
  "values/ic_launcher_background.xml",
  ...Object.keys(DENSITIES).map((d) => `mipmap-${d}/ic_launcher_foreground.png`),
]) {
  if (existsSync(join(RES, stale))) rmSync(join(RES, stale));
}

const browser = await openBrowser();
try {
  // Android 7 has no adaptive icons and no night icons: dark scheme PNGs,
  // 48dp with the usual 1dp-ish system margin.
  for (const [density, k] of Object.entries(DENSITIES)) {
    const dir = join(RES, `mipmap-${density}`);
    const size = 48 * k;
    const inner = size * 0.92;
    for (const [file, radius] of [["ic_launcher.png", `${inner * 0.22}px`], ["ic_launcher_round.png", "50%"]]) {
      await render(browser, `<div style="padding:${(size - inner) / 2}px">${tile(inner, SCHEMES.dark, radius)}</div>`, {
        width: size, height: size, out: join(dir, file), transparent: true,
      });
    }
  }

  // Play listing icon: 512×512, full bleed (Play applies its own rounded mask).
  // "2px" corners keep a few translucent pixels, so the PNG stays 32-bit as Play asks.
  await render(browser, tile(512, SCHEMES.dark, "2px"), {
    width: 512, height: 512, out: join(ROOT, "fastlane/metadata/android/en-US/images/icon.png"), transparent: true,
  });

  // Previews of both schemes and the themed tint, for review only.
  const preview = join(tmpdir(), "noirly-flow-icon-preview.png");
  const themed = { bg: "#2f3a2a", mark: "#c9e7b4" };
  await render(
    browser,
    `<div style="display:flex;gap:32px;padding:32px;background:#777">
      ${[SCHEMES.light, SCHEMES.dark, themed].map((s) => tile(192, s, "50%")).join("")}
    </div>`,
    { width: 32 * 4 + 192 * 3, height: 256, out: preview },
  );
  console.log("Icons written. Preview:", preview);
} finally {
  await browser.close();
}
